import assert from 'node:assert/strict';
import '../ozon-erp-collector-extension/store-scanner-core.js';
import '../ozon-erp-collector-extension/category-core.js';
const c=globalThis.OzonCategoryCore;
const url='https://www.ozon.ru/category/instrumenty-12345/';
assert.equal(c.normalizeUrl(url+'?page=3&from=abc'),url);
assert.equal(c.keyFromUrl(url),'category:12345');
assert.equal(c.normalizeUrl('https://evil.example/category/instrumenty-12345/'),'');
assert.equal(c.normalizeUrl('https://www.ozon.ru/seller/shop-12345/'),'');
assert.equal(c.normalizeUrl('https://www.ozon.ru@wrong.example/category/12345/'),'');
assert.equal(c.samePage(url+'?page=2',url),true);
assert.equal(c.samePage('https://www.ozon.ru/category/other-12346/',url),false);
assert.equal(c.paginationUrl(url+'?page=2',url),url+'?page=2');
assert.equal(c.paginationUrl(url+'?page=9999',url),'');
assert.equal(c.paginationUrl(url+'?page=2&sort=other',url),'');
const china='https://www.ozon.ru/highlight/tovary-iz-kitaya-935133/?category=12345';
assert.equal(c.normalizeUrl(china),china);assert.equal(c.keyFromUrl(china),'china-category:12345');
assert.equal(c.samePage(china,url),false,'different sources with the same number stay distinct');
assert.equal(c.normalizeUrl(china+'&page=2'),china);
assert.equal(c.paginationUrl(china+'&page=2',china),china+'&page=2');
assert.equal(c.paginationUrl('https://www.ozon.ru/highlight/tovary-iz-kitaya-935133/?page=2&category=12345',china),china+'&page=2');
for(const invalid of [china+'&category=12345',china+'&page=2&page=3',china+'&sort=price',china.replace('935133','222333'),china.split('?')[0],china+'#extra',china.replace('12345','abc'),china+'&page=0'])assert.equal(c.normalizeUrl(invalid),'',invalid);
assert.equal(c.paginationUrl(china.replace('12345','999')+'&page=2',china),'');
assert.equal(c.paginationUrl(url+'?page=2',china),'');
assert.deepEqual(c.parseUrls([url,china,china+'&page=2']).urls,[url,china]);
const parsed=c.parseUrls([url,url+'?page=1','https://www.ozon.ru/category/other-6789/','https://example.com/'].join('\n'));
assert.equal(parsed.urls.length,2);assert.equal(parsed.duplicateCount,1);assert.equal(parsed.invalid.length,1);
const opt=c.validateOptions({targetCount:'25',minPrice:'20',maxPrice:'100'});
assert.deepEqual(opt,{targetCount:25,minPrice:20,maxPrice:100});
assert.deepEqual(c.validateOptions({targetCount:1,minPrice:'',maxPrice:''}),{targetCount:1,minPrice:null,maxPrice:null});
assert.throws(()=>c.validateOptions({targetCount:0}));assert.throws(()=>c.validateOptions({targetCount:1000}));assert.throws(()=>c.validateOptions({targetCount:5,minPrice:100,maxPrice:10}));
const base={sku:'123',qualified:true,price:'88,20',name:'工具',category:'扳手',link:'https://www.ozon.ru/product/wrench-123/',shippingRisk:{type:'clear'}};
assert.equal(c.qualifiedProduct(base,opt),true);
assert.equal(c.qualifiedProduct({...base,link:'https://www.ozon.ru/product/wrench-124/'},opt),false);
assert.equal(c.qualifiedProduct({...base,qualified:false},opt),false);
assert.equal(c.qualifiedProduct({...base,shippingRisk:{type:'suspected_prohibited'}},opt),false);
assert.equal(c.qualifiedProduct({...base,name:'电子烟'},opt),false);
assert.equal(c.qualifiedProduct({...base,price:'110,00'},opt),false);
assert.equal(c.qualifiedProduct({...base,price:''},opt),false);
assert.equal(c.priceAllowed({...base,price:'88 ₽'},opt),false);
const rub=c.validateOptions({targetCount:5,minPrice:'20',maxPrice:'100',pageMinRub:'500',pageMaxRub:'2500'});
assert.deepEqual(rub,{targetCount:5,minPrice:20,maxPrice:100,pageMinRub:500,pageMaxRub:2500});
for(const bad of [{pageMinRub:'500'},{pageMaxRub:'2500'},{pageMinRub:'500.5',pageMaxRub:2500},{pageMinRub:2500,pageMaxRub:500},{pageMinRub:-1,pageMaxRub:500},{pageMinRub:0,pageMaxRub:10000001}])assert.throws(()=>c.validateOptions({targetCount:5,...bad}));
const filtered=china+'&currency_price=500.000%3B2500.000';
const filteredNormal=url+'?currency_price=500.000%3B2500.000';
assert.equal(c.pricePageUrl(china,rub),filtered);
assert.equal(c.pricePageUrl(url,rub),filteredNormal);
assert.equal(c.pricePageUrl(china,opt),china);
assert.equal(c.exactPageUrl(china+'&__rr=1&abt_att=1&currency_price=500.000%3B2500.000'),filtered);
assert.equal(c.exactPageUrl(filtered+'&__rr=2'),'');
assert.equal(c.exactPageUrl(filtered+'&currency_price=1.000%3B9999.000'),'');
assert.equal(c.exactPageUrl(filtered.replace('500.000','-1.000')),'');
assert.equal(c.paginationUrl(filtered+'&page=2',filtered),filtered+'&page=2');
assert.equal(c.paginationUrl(filteredNormal+'&page=2',filteredNormal),filteredNormal+'&page=2');
assert.equal(c.paginationUrl(china+'&page=2',filtered),'','must not lose filter on pagination');
assert.equal(c.paginationUrl(filtered.replace('2500.000','3000.000')+'&page=2',filtered),'','must not widen filter');
assert.equal(c.paginationUrl(filtered+'&page=2',china),'','unfiltered tasks must not adopt another filter');
assert.equal(c.paginationUrl(filtered+'&page=2&sort=price',filtered),'');
assert.equal(c.priceAllowed({...base,price:'110'},rub),false,'RUB is not a substitute for CNY');
assert.equal(c.capturedRubPrice('1 480 ₽'), 1480);
assert.equal(c.capturedRubPrice('327,28 ¥'), null);
assert.equal(c.capturedAnyPrice('1 480 ₽'), 1480);
assert.equal(c.priceAllowed({ ...base, price: '1 480 ₽' }, { minPrice: 100, maxPrice: 200, fxRate: 12 }), true);
assert.equal(c.priceAllowed({ ...base, price: '900 ₽' }, { minPrice: 100, maxPrice: 200, fxRate: 12 }), false);
assert.equal(c.priceAllowed({ ...base, price: '1 480 ₽' }, { minPrice: null, maxPrice: null }), true);
assert.equal(c.priceAllowed({ ...base, price: '88 ₽' }, opt), false);
assert.equal(c.validateOptions({ targetCount: 10, minPrice: '100', pageMinRub: '1300', pageMaxRub: '30000', fxRate: 12.37 }).fxRate, 12.37);
assert.equal(c.validateOptions({ targetCount: 50, perCategoryLimit: '20' }).perCategoryLimit, 20);
assert.equal('perCategoryLimit' in c.validateOptions({ targetCount: 50, perCategoryLimit: '' }), false);
for (const badLimit of ['0', '501', '12.5', 'abc']) assert.throws(() => c.validateOptions({ targetCount: 50, perCategoryLimit: badLimit }));
console.log('Category core URL, pagination, target, price, positive label, identity and risk tests passed.');
